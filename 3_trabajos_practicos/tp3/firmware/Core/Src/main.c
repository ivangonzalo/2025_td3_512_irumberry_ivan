void Set_PWM_Frequency(TIM_HandleTypeDef *htim, uint32_t freq)
{
    uint32_t timer_clk = 72000000; // 72 MHz
    uint32_t prescaler = 71;       // Dividir por 72
    uint32_t arr;

    // Calculamos el ARR para la frecuencia deseada
    arr = (timer_clk / ((prescaler + 1) * freq)) - 1; //Counter Period (ARR) Si f=10Khz --> arr=99

    // Paramos el timer
    HAL_TIM_PWM_Stop(htim, TIM_CHANNEL_1);

    // Actualizamos prescaler y period
    htim->Instance->PSC = prescaler;
    htim->Instance->ARR = arr;

    // Opcional: actualizar CCR para mantener duty al 50%
    htim->Instance->CCR1 = (arr + 1) / 2;

    // Reiniciamos el contador y arrancamos de nuevo
    HAL_TIM_PWM_Start(htim, TIM_CHANNEL_1);
}
